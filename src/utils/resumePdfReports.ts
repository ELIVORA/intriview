import { jsPDF } from "jspdf";

function text(value: unknown, fallback = "Not provided"): string {
  const s = String(value ?? "").trim();
  return s || fallback;
}

function list(values: unknown, fallback = "Not provided"): string[] {
  if (!Array.isArray(values)) return fallback ? [fallback] : [];
  const out = values.map((v) => String(v ?? "").trim()).filter(Boolean);
  return out.length ? out : [fallback];
}

function addHeader(doc: jsPDF, title: string, subtitle?: string) {
  doc.setFillColor(23, 37, 84);
  doc.rect(0, 0, 210, 28, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(18);
  doc.text(title, 16, 16);
  if (subtitle) {
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8);
    doc.text(subtitle, 16, 22);
  }
  doc.setTextColor(30, 41, 59);
}

function section(doc: jsPDF, title: string, y: number): number {
  doc.setFillColor(241, 245, 249);
  doc.roundedRect(14, y, 182, 8, 2, 2, "F");
  doc.setFont("helvetica", "bold");
  doc.setFontSize(10);
  doc.setTextColor(30, 41, 59);
  doc.text(title.toUpperCase(), 18, y + 5.5);
  return y + 13;
}

function wrapped(doc: jsPDF, value: string, x: number, y: number, width: number, fontSize = 9, lineHeight = 4.5): number {
  doc.setFont("helvetica", "normal");
  doc.setFontSize(fontSize);
  const lines = doc.splitTextToSize(value, width) as string[];
  for (const line of lines) {
    if (y > 278) { doc.addPage(); addHeader(doc, "Interview Cracker Report"); y = 38; }
    doc.text(line, x, y);
    y += lineHeight;
  }
  return y;
}

function bulletList(doc: jsPDF, values: string[], x: number, y: number, width: number): number {
  for (const value of values) {
    doc.setFont("helvetica", "bold");
    doc.setFontSize(8.5);
    doc.text("-", x, y);
    y = wrapped(doc, value, x + 4, y, width - 4, 8.5, 4.2) + 1.5;
    if (y > 278) { doc.addPage(); addHeader(doc, "Interview Cracker Report"); y = 38; }
  }
  return y;
}

function addFooter(doc: jsPDF) {
  const pages = doc.getNumberOfPages();
  for (let page = 1; page <= pages; page++) {
    doc.setPage(page);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(7);
    doc.setTextColor(100, 116, 139);
    doc.text(`Interview Cracker • Page ${page} of ${pages}`, 16, 289);
  }
}

function save(doc: jsPDF, filename: string) {
  addFooter(doc);
  doc.save(filename);
}

export function downloadAtsReport(analysis: any) {
  const doc = new jsPDF();
  addHeader(doc, "ATS Resume Report", `${text(analysis?.personalInfo?.fullName, "Candidate")} • Generated by Interview Cracker`);
  let y = 38;
  doc.setFont("helvetica", "bold"); doc.setFontSize(28); doc.setTextColor(37, 99, 235);
  doc.text(`${Number(analysis?.atsScore || 0)}/100`, 16, y); y += 10;
  doc.setFontSize(10); doc.setTextColor(71, 85, 105); doc.setFont("helvetica", "normal");
  doc.text("ATS compatibility score based on the uploaded resume analysis.", 16, y); y += 10;

  y = section(doc, "Candidate", y);
  y = wrapped(doc, `${text(analysis?.personalInfo?.email)} | ${text(analysis?.personalInfo?.phone)} | ${text(analysis?.personalInfo?.location)}`, 16, y, 178) + 4;
  y = wrapped(doc, `Target role: ${list(analysis?.candidateProfile?.targetRoles).join(", ")}`, 16, y, 178) + 6;

  y = section(doc, "Resume Strengths", y);
  y = bulletList(doc, list(analysis?.resumeQualityReport?.strengths, "No strengths recorded."), 18, y, 174) + 4;
  y = section(doc, "Weaknesses", y);
  y = bulletList(doc, list(analysis?.resumeQualityReport?.weaknesses, "No weaknesses recorded."), 18, y, 174) + 4;
  y = section(doc, "Keyword Findings", y);
  y = wrapped(doc, `Relevant: ${list(analysis?.keywordAnalysis?.relevant).join(", ")}`, 16, y, 178) + 3;
  y = wrapped(doc, `Missing: ${list(analysis?.keywordAnalysis?.missing).join(", ")}`, 16, y, 178) + 3;
  y = wrapped(doc, `Overused: ${list(analysis?.keywordAnalysis?.overused, "None recorded.").join(", ")}`, 16, y, 178) + 3;
  y = section(doc, "Recommendations", y);
  y = bulletList(doc, list((analysis?.resumeQualityReport?.recommendations || []).map((r: any) => `${r.action || "Recommendation"} - ${r.impact || ""}`), "No recommendations recorded."), 18, y, 174);
  save(doc, "ATS_Report.pdf");
}

