export function downloadImprovedResume(analysis: any) {
  const doc = new jsPDF();
  const pi = analysis?.personalInfo || {};
  const cp = analysis?.candidateProfile || {};
  doc.setTextColor(15, 23, 42);
  doc.setFont("helvetica", "bold"); doc.setFontSize(22);
  doc.text(text(pi.fullName, "Candidate"), 16, 18);
  doc.setFont("helvetica", "normal"); doc.setFontSize(8.5); doc.setTextColor(71,85,105);
  doc.text([text(pi.email), text(pi.phone), text(pi.location)].filter(Boolean).join(" | "), 16, 24);
  let y = 34;
  const resumeSection = (title: string) => { y = section(doc, title, y); };
  const addBody = (value: string) => { y = wrapped(doc, value, 16, y, 178, 9.5, 4.8) + 5; };

  resumeSection("Professional Summary");
  addBody(text(analysis?.resumeImprovement?.improvedProfessionalSummary));
  if (text(cp.targetRoles, "").trim()) { resumeSection("Target Role"); addBody(list(cp.targetRoles).join(", ")); }
  resumeSection("Skills");
  addBody(`Languages: ${list(analysis?.skillsAnalysis?.programmingLanguages).join(", ")}\nFrameworks: ${list(analysis?.skillsAnalysis?.frameworks).join(", ")}\nTools: ${list(analysis?.skillsAnalysis?.tools).join(", ")}\nDatabases: ${list(analysis?.skillsAnalysis?.databases).join(", ")}\nCloud: ${list(analysis?.skillsAnalysis?.cloud).join(", ")}`);
  if (Array.isArray(analysis?.workExperience) && analysis.workExperience.length) {
    resumeSection("Experience");
    for (const exp of analysis.workExperience) { addBody(`${text(exp.title)} - ${text(exp.company)}${exp.duration ? ` (${exp.duration})` : ""}\n${text(exp.description)}`); }
  }
  resumeSection("Projects");
  const projects = Array.isArray(analysis?.projectsAnalysis) ? analysis.projectsAnalysis : [];
  for (const project of projects.filter((x: any) => x && typeof x === "object")) {
    addBody(`${text(project.title)}\n${text(project.description)}\nTechnologies: ${list(project.techStack).join(", ")}`);
  }
  if (Array.isArray(analysis?.achievements) && analysis.achievements.length) { resumeSection("Achievements"); addBody(analysis.achievements.map((a:any)=>text(a)).join("\n")); }
  resumeSection("Education");
  addBody(`${text(pi.degree)} - ${text(pi.branch)}\n${text(pi.college)}${pi.graduationYear ? ` • ${pi.graduationYear}` : ""}${pi.cgpa ? ` • CGPA/GPA: ${pi.cgpa}` : ""}`);
  save(doc, "Improved_Resume.pdf");
}

